//! Pre-render all routes from the Leptos SSR app to static HTML.
//!
//! Cross-platform (Linux/macOS/Windows). Zero extra dependencies — uses only std.
//! Reads routes from the build-generated `routes.txt` manifest.
//!
//! Usage: `cargo run --bin prerender --features ssr --release`

use std::fs;
use std::io::{Read, Write};
use std::net::TcpStream;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::thread;
use std::time::{Duration, Instant};

fn main() {
    let site_dir = PathBuf::from("target/site");
    let dist_dir = PathBuf::from("dist");
    let port: u16 = env_port().unwrap_or(3000);

    let server_bin = if cfg!(windows) {
        PathBuf::from("target/release/commitbee-web.exe")
    } else {
        PathBuf::from("target/release/commitbee-web")
    };

    println!("==> Starting pre-render...");

    // Clean dist
    if dist_dir.exists() {
        fs::remove_dir_all(&dist_dir).expect("Failed to clean dist directory");
    }
    fs::create_dir_all(&dist_dir).expect("Failed to create dist directory");

    // Start the server
    let mut server = Command::new(&server_bin)
        .env("LEPTOS_SITE_ADDR", format!("127.0.0.1:{port}"))
        .env("LEPTOS_HASH_FILES", "true")
        .spawn()
        .unwrap_or_else(|e| {
            eprintln!(
                "ERROR: Failed to start server at {}: {e}",
                server_bin.display()
            );
            std::process::exit(1);
        });

    // Wait for server to be ready
    if !wait_for_server(port, Duration::from_secs(30)) {
        eprintln!("ERROR: Server failed to start within 30s");
        server.kill().ok();
        std::process::exit(1);
    }
    println!("==> Server ready on port {port}");

    // Find routes.txt
    let routes_file = find_routes_txt().unwrap_or_else(|| {
        eprintln!("ERROR: routes.txt not found in target/build/commitbee-web-*/out/");
        server.kill().ok();
        std::process::exit(1);
    });
    println!("==> Using routes from: {}", routes_file.display());

    // Read routes
    let routes_content = fs::read_to_string(&routes_file).expect("Failed to read routes.txt");
    let routes: Vec<&str> = routes_content.lines().filter(|l| !l.is_empty()).collect();

    // Pre-render each route
    let mut rendered = 0usize;
    for route in &routes {
        let output_path = if *route == "/" {
            dist_dir.join("index.html")
        } else {
            dist_dir.join(format!("{}.html", route.trim_start_matches('/')))
        };

        if let Some(parent) = output_path.parent() {
            fs::create_dir_all(parent).ok();
        }

        match http_get("127.0.0.1", port, route) {
            Ok(body) => {
                fs::write(&output_path, body).expect("Failed to write HTML");
                println!("    {route} -> {}", output_path.display());
                rendered += 1;
            }
            Err(e) => {
                eprintln!("    WARNING: Failed to render {route}: {e}");
            }
        }
    }

    // Copy static assets
    println!("==> Copying static assets...");
    let pkg_src = site_dir.join("pkg");
    let pkg_dst = dist_dir.join("pkg");
    if pkg_src.exists() {
        copy_dir_recursive(&pkg_src, &pkg_dst).expect("Failed to copy pkg/");
    }

    let public_dir = PathBuf::from("public");
    if public_dir.exists() {
        copy_dir_recursive(&public_dir, &dist_dir).expect("Failed to copy public/");
    }

    // Copy search index (generated by build.rs into target/site/)
    let search_index_src = site_dir.join("search_index.json");
    if search_index_src.exists() {
        fs::copy(&search_index_src, dist_dir.join("search_index.json"))
            .expect("Failed to copy search_index.json");
        println!("    search_index.json -> dist/search_index.json");
    }

    // Generate 404.html from the pre-rendered /not-found route
    let not_found_path = dist_dir.join("not-found.html");
    let fallback_path = dist_dir.join("index.html");
    let source_404 = if not_found_path.exists() {
        &not_found_path
    } else {
        &fallback_path
    };
    if source_404.exists() {
        fs::copy(source_404, dist_dir.join("404.html")).ok();
        println!("    {} -> dist/404.html", source_404.display());
    }

    // Generate robots.txt
    let base_url = env_base_url().unwrap_or_else(|| "https://commitbee.buzz".to_string());
    let robots = format!("User-agent: *\nAllow: /\n\nSitemap: {base_url}/sitemap.xml\n");
    fs::write(dist_dir.join("robots.txt"), &robots).expect("Failed to write robots.txt");
    println!("    robots.txt -> dist/robots.txt");

    // Generate sitemap.xml
    let mut sitemap = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n",
    );
    for route in routes
        .iter()
        .filter(|r| **r != "/not-found" && **r != "/docs")
    {
        let priority = if *route == "/" { "1.0" } else { "0.8" };
        let loc = if *route == "/" {
            format!("{base_url}/")
        } else {
            format!("{base_url}{route}")
        };
        let lastmod = if let Some(slug) = route.strip_prefix("/docs/") {
            git_lastmod(&format!("content/docs/{slug}.md"))
        } else {
            git_lastmod(".")
        };
        let lastmod_tag = lastmod
            .map(|d| format!("    <lastmod>{d}</lastmod>\n"))
            .unwrap_or_default();
        sitemap.push_str(&format!(
            "  <url>\n    <loc>{loc}</loc>\n{lastmod_tag}    <priority>{priority}</priority>\n  </url>\n"
        ));
    }
    sitemap.push_str("</urlset>\n");
    fs::write(dist_dir.join("sitemap.xml"), &sitemap).expect("Failed to write sitemap.xml");
    println!("    sitemap.xml -> dist/sitemap.xml");

    // Stop server
    server.kill().ok();
    server.wait().ok();

    let file_count = count_files(&dist_dir);
    println!("==> Pre-render complete. Output in {}/", dist_dir.display());
    println!("    Routes rendered: {rendered}");
    println!("    Total files: {file_count}");
}

fn env_port() -> Option<u16> {
    std::env::var("PRERENDER_PORT").ok()?.parse().ok()
}

fn env_base_url() -> Option<String> {
    std::env::var("SITE_BASE_URL").ok()
}

/// ISO-8601 timestamp of the last commit touching `path`, if available.
fn git_lastmod(path: &str) -> Option<String> {
    let out = Command::new("git")
        .args(["log", "-1", "--format=%cI", "--", path])
        .output()
        .ok()?;
    let s = String::from_utf8(out.stdout).ok()?.trim().to_string();
    (!s.is_empty()).then_some(s)
}

fn wait_for_server(port: u16, timeout: Duration) -> bool {
    let start = Instant::now();
    while start.elapsed() < timeout {
        if TcpStream::connect(format!("127.0.0.1:{port}")).is_ok() {
            return true;
        }
        thread::sleep(Duration::from_millis(500));
    }
    false
}

/// Minimal HTTP/1.0 GET — no dependencies needed.
fn http_get(host: &str, port: u16, path: &str) -> Result<String, Box<dyn std::error::Error>> {
    let addr = format!("{host}:{port}");
    let mut stream = TcpStream::connect(&addr)?;
    stream.set_read_timeout(Some(Duration::from_secs(30)))?;

    let request = format!("GET {path} HTTP/1.0\r\nHost: {addr}\r\nConnection: close\r\n\r\n");
    stream.write_all(request.as_bytes())?;
    stream.flush()?;

    let mut response = String::new();
    stream.read_to_string(&mut response)?;

    // Validate HTTP status code — reject non-200 responses (e.g. 404, 500).
    let status_line = response.lines().next().unwrap_or("");
    let status_code: u16 = status_line
        .split_whitespace()
        .nth(1)
        .and_then(|c| c.parse().ok())
        .unwrap_or(0);
    if status_code != 200 {
        return Err(format!("HTTP {status_code} for {path}: {status_line}").into());
    }

    // Split headers from body at the blank line
    let body_start = response.find("\r\n\r\n").map(|i| i + 4).unwrap_or(0);
    Ok(response[body_start..].to_string())
}

/// Find the most recently modified `routes.txt` under `target/` that
/// belongs to the commitbee-web build output. Using the newest avoids
/// picking a stale artifact from a prior build.
fn find_routes_txt() -> Option<PathBuf> {
    let build_dir = PathBuf::from("target");
    let mut candidates = collect_routes_files(&build_dir);
    // Sort ascending by mtime; last element is the newest.
    candidates.sort_by_key(|p| p.metadata().and_then(|m| m.modified()).ok());
    candidates.into_iter().last()
}

fn collect_routes_files(dir: &Path) -> Vec<PathBuf> {
    let mut result = Vec::new();
    if !dir.is_dir() {
        return result;
    }
    let Ok(entries) = fs::read_dir(dir) else {
        return result;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_file()
            && path.file_name().is_some_and(|f| f == "routes.txt")
            && path.to_string_lossy().contains("commitbee-web")
        {
            result.push(path);
        } else if path.is_dir() {
            result.extend(collect_routes_files(&path));
        }
    }
    result
}

fn copy_dir_recursive(src: &Path, dst: &Path) -> std::io::Result<()> {
    fs::create_dir_all(dst)?;
    for entry in fs::read_dir(src)?.flatten() {
        // Skip dotfiles (.DS_Store etc.) — nothing hidden is intentionally deployed.
        if entry.file_name().to_string_lossy().starts_with('.') {
            continue;
        }
        let src_path = entry.path();
        let dst_path = dst.join(entry.file_name());
        if src_path.is_dir() {
            copy_dir_recursive(&src_path, &dst_path)?;
        } else {
            fs::copy(&src_path, &dst_path)?;
        }
    }
    Ok(())
}

fn count_files(dir: &Path) -> usize {
    let mut count = 0;
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_file() {
                count += 1;
            } else if path.is_dir() {
                count += count_files(&path);
            }
        }
    }
    count
}
